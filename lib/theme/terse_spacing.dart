/// Spacing scale of the Terse UI, in logical pixels.
abstract class TerseSpacing {
  /// Tight gaps inside a text stack, e.g. between a label and its value.
  static const double xxs = 4;

  /// Gaps between chips and between small controls.
  static const double xs = 8;

  /// Gaps between cards and between buttons.
  static const double sm = 12;

  /// Card padding.
  static const double md = 16;

  /// Horizontal padding of a screen.
  static const double lg = 20;

  /// Gaps between sections.
  static const double xl = 24;

  /// Large separations, e.g. above a screen title.
  static const double xxl = 32;
}
